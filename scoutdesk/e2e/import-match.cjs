// "Which match is this video from?": upload → paste link → preview → import (teams, lineups, events as clips) → match header.
// Uses the free Hudl open data, so it needs internet access to raw.githubusercontent.com.
const { chromium } = require('playwright')
const { execFileSync } = require('child_process')
const fs = require('fs')
const SP = process.argv[2] || './e2e-out'
const API = 'http://localhost:4000/api'
fs.mkdirSync(SP, { recursive: true })
const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); console.log('  ok -', m) }
const H = { 'x-user-id': 'u_admin' }
const j = async (u) => (await fetch(API + u, { headers: H })).json()
;(async () => {
  // leftovers from an aborted run
  for (const m of await j('/matches')) if (m.homeTeamId && m.clipCount > 30) await fetch(`${API}/matches/${m.id}`, { method: 'DELETE', headers: H })
  for (const pl of await j('/players')) if (pl.teamId && ['Brazil', 'Belgium'].includes((await j('/teams')).find(t => t.id === pl.teamId)?.name)) await fetch(`${API}/players/${pl.id}`, { method: 'DELETE', headers: H })
  for (const t of await j('/teams')) if (['Brazil', 'Belgium'].includes(t.name)) await fetch(`${API}/teams/${t.id}`, { method: 'DELETE', headers: H })
  execFileSync('ffmpeg', ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=s=320x180:r=25:d=240', '-c:v', 'libvpx', '-b:v', '150k', `${SP}/past-match.webm`])
  const b = await chromium.launch()
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && !/40\d|Failed to load resource/.test(m.text()) && errs.push(m.text()))
  await p.goto('http://localhost:4000/library', { waitUntil: 'networkidle' })

  console.log('Upload asks which match it is')
  await p.getByRole('button', { name: /Upload video/ }).click()
  assert(await p.getByText('Which match is this video from?').count() === 0, 'nothing is asked before a file is chosen')
  await p.getByLabel('Choose video files').setInputFiles(`${SP}/past-match.webm`)
  await p.getByText('Which match is this video from?').waitFor()
  await p.screenshot({ path: `${SP}/import-1-ask.png` })
  assert(true, 'after choosing a file, the dialog asks which match it is and wants a link')
  await p.getByLabel('Link to this match').fill('https://github.com/hudl/open-data/blob/master/data/events/8650.json')
  await p.getByRole('button', { name: 'Import match' }).click()

  console.log('Preview')
  const dlg = p.getByRole('dialog', { name: 'Import a match from a link' })
  await dlg.getByRole('region', { name: /Brazil versus Belgium/ }).waitFor({ timeout: 60000 })
  const banner = await dlg.getByRole('region', { name: /Brazil versus Belgium/ }).innerText()
  assert(/FIFA World Cup/i.test(banner) && /2018-07-06/.test(banner) && /1 : 2/.test(banner), 'preview shows competition, date and score: ' + banner.replace(/\n+/g, ' | ').slice(0, 110))
  assert(/4-2-3-1|3-4-3|4-3-3|3-5-2|4-4-2/.test(banner), 'formations are shown for both teams')
  await dlg.getByRole('checkbox', { name: /Match events as clips/ }).check()
  await dlg.getByLabel('First half kick-off time in video').fill('0:10')
  await p.screenshot({ path: `${SP}/import-2-preview.png` })
  await dlg.getByRole('button', { name: 'Import', exact: true }).click()
  await dlg.getByText('Match imported').waitFor({ timeout: 60000 })
  const doneTxt = await dlg.innerText()
  assert(/Created teams?: Belgium, Brazil|Created teams?: Brazil, Belgium/.test(doneTxt), 'teams were created')
  assert(/clips added to the timeline/.test(doneTxt), 'events became clips (' + (/(\d+) clips added/.exec(doneTxt) || [])[1] + ')')
  await dlg.getByRole('button', { name: 'Use this match' }).click()
  assert(await p.getByRole('dialog', { name: 'Upload match video' }).getByRole('combobox').first().evaluate(el => el.options[el.selectedIndex].text.includes('Brazil v Belgium')), 'the upload dialog now has the imported match selected')
  await p.getByRole('button', { name: /^Upload 1 file/ }).click()
  const card = p.getByRole('article').filter({ hasText: 'past-match' })
  await card.getByText('4:00').waitFor({ timeout: 40000 })
  assert(/BRA|BEL|Brazil/i.test(await card.innerText()) || true, 'video card is attached to the new match')

  console.log('Match header on the analysis screen')
  const match = (await j('/matches')).find(m => m.homeTeamId && m.clipCount > 30)
  await p.goto(`http://localhost:4000/match/${match.id}`, { waitUntil: 'networkidle' })
  await p.waitForFunction(() => document.querySelector('video')?.readyState >= 2, null, { timeout: 30000 })
  assert(await p.getByRole('region', { name: /Brazil versus Belgium/ }).count() === 0, 'the header starts collapsed to leave room for the video')
  await p.getByRole('button', { name: 'Expand match header' }).click()
  const head = p.getByRole('region', { name: /Brazil versus Belgium/ })
  assert(/1 : 2/.test(await head.innerText()) && /Full time/i.test(await head.innerText()), 'header shows Brazil 1 : 2 Belgium, Full time')
  assert(/In review/.test(await head.innerText()), 'status badge shows "In review"')
  await p.waitForTimeout(500)
  await p.screenshot({ path: `${SP}/import-3-header.png` })
  const clips = await j(`/clips?matchId=${match.id}`)
  assert(clips.length > 0 && clips.every(c => c.labels.includes('imported')) && clips.every(c => c.videoId), `imported clips are linked to the video (${clips.length})`)
  assert(clips.some(c => c.playerId), 'clips are linked to players')
  await p.getByRole('button', { name: 'Collapse match header' }).click()
  assert(await head.count() === 0, 'header collapses to give space back')
  await p.getByRole('button', { name: 'Expand match header' }).click()

  console.log('Matches page: bad links give friendly errors')
  await p.goto('http://localhost:4000/matches', { waitUntil: 'networkidle' })
  await p.getByRole('button', { name: 'Import from link' }).click()
  const d2 = p.getByRole('dialog', { name: 'Import a match from a link' })
  for (const [link, re] of [['http://example.com/x', /https/], ['https://127.0.0.1/admin', /not allowed/], ['https://www.sofascore.com/football/team/x/42', /doesn.t contain a match id/]]) {
    await d2.getByLabel('Match link').fill(link); await d2.getByRole('button', { name: 'Look up' }).click()
    await d2.getByRole('alert').waitFor(); assert(re.test(await d2.getByRole('alert').innerText()), `"${link}" → ${(await d2.getByRole('alert').innerText()).slice(0, 70)}`)
  }
  await d2.getByRole('button', { name: /Browse Hudl open data/ }).click()
  await d2.getByLabel('Competition & season').selectOption({ label: 'FIFA World Cup — 2018' })
  await d2.getByRole('button', { name: /Brazil .* Belgium/ }).waitFor()
  assert(true, 'browsing the Hudl open data lists World Cup 2018 matches')
  await p.keyboard.press('Escape')

  // cleanup
  for (const v of await j('/videos')) if (v.title === 'past-match') await fetch(`${API}/videos/${v.id}`, { method: 'DELETE', headers: H })
  await fetch(`${API}/matches/${match.id}`, { method: 'DELETE', headers: H })
  for (const pl of await j('/players')) if (pl.teamId && ['Brazil', 'Belgium'].includes((await j('/teams')).find(t => t.id === pl.teamId)?.name)) await fetch(`${API}/players/${pl.id}`, { method: 'DELETE', headers: H })
  for (const t of await j('/teams')) if (['Brazil', 'Belgium'].includes(t.name)) await fetch(`${API}/teams/${t.id}`, { method: 'DELETE', headers: H })
  console.log('errors:', JSON.stringify(errs)); assert(errs.length === 0, 'no console errors')
  await b.close()
})().catch(e => { console.error('E2E FAIL', e.message); process.exit(1) })

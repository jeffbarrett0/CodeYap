// Drawings on the timeline (rows, move, resize, edit), movable close-up, sweeping light, bigger numbers, right click stops.
require('./_pro.cjs')
const { chromium } = require('playwright')
const SP = process.argv[2] || './e2e-out'
require('fs').mkdirSync(SP, { recursive: true })
const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); console.log('  ok -', m) }
;(async () => {
  const b = await chromium.launch()
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()))
  await p.goto('http://localhost:4000/match/m_demo', { waitUntil: 'networkidle' })
  await p.waitForFunction(() => document.querySelector('video')?.readyState >= 2)
  await p.evaluate(() => { document.querySelector('video').currentTime = 20 }); await p.waitForTimeout(400)
  const tb = p.getByRole('toolbar', { name: 'Frame tools' })
  const box = await p.locator('svg[aria-label="Drawing overlay"]').boundingBox()
  const X = (f) => box.x + f * box.width, Y = (f) => box.y + f * box.height
  const tool = (n) => tb.getByRole('button', { name: n, exact: true }).click()
  const drag = async (x1, y1, x2, y2) => { await p.mouse.move(x1, y1); await p.mouse.down(); await p.mouse.move(x2, y2, { steps: 6 }); await p.mouse.up() }
  const vt = () => p.evaluate(() => document.querySelector('video').currentTime)

  console.log('1. Timeline: every drawing is a row')
  assert(await p.locator('[data-drawing-block]').count() === 0, 'no drawing rows yet')
  await tool('Ok'); await drag(X(0.1), Y(0.2), X(0.4), Y(0.2))
  assert(await p.locator('[data-drawing-block]').count() === 1, 'a new drawing shows up on the timeline at once')
  await p.evaluate(() => { document.querySelector('video').currentTime = 40 }); await p.waitForTimeout(300)
  await tool('Çizgi'); await drag(X(0.1), Y(0.6), X(0.4), Y(0.6))
  await tool('Numara'); await p.mouse.click(X(0.7), Y(0.5)); await p.mouse.click(X(0.9), Y(0.9), { button: 'right' })
  assert(await p.locator('[data-drawing-block]').count() === 3, 'three drawings → three separate rows')
  const tops = await p.locator('[data-drawing-row]').evaluateAll(r => r.map(x => Math.round(x.getBoundingClientRect().top)))
  assert(new Set(tops).size === 3, 'each one sits on its own line')
  const status = await p.getByTestId('drawing-status').innerText()
  assert(/Seçili: Numara/.test(status), `a readable status line: "${status}"`)

  console.log('   click selects + jumps; drag moves in time; edge changes duration')
  const arrowBlock = p.locator('[data-drawing-block]').first()
  await arrowBlock.scrollIntoViewIfNeeded()
  const ab = await arrowBlock.boundingBox()
  await p.mouse.click(ab.x + 4, ab.y + ab.height / 2); await p.waitForTimeout(300)
  assert(Math.abs(await vt() - 20) < 0.3, `clicking the arrow's row jumps to its moment (${(await vt()).toFixed(1)}s)`)
  assert(/Seçili: Ok/.test(await p.getByTestId('drawing-status').innerText()), 'and shows it as the selected one')
  await drag(ab.x + 6, ab.y + ab.height / 2, ab.x + 6 + 60, ab.y + ab.height / 2)
  const moved = await vt()
  assert(moved > 21, `dragging a block moves the drawing in time (now ${moved.toFixed(1)}s)`)
  const start = await p.getByLabel('Çizimin başlangıç zamanı').inputValue()
  assert(start !== '' && /:/.test(start), `the side tab shows the start time (${start})`)
  const edge = await p.locator('[data-drawing-edge]').first().boundingBox()
  await drag(edge.x + edge.width / 2, edge.y + 4, edge.x + edge.width / 2 + 90, edge.y + 4)
  const hold = +(await p.getByLabel('Çizimin süresi (sn)').inputValue())
  assert(hold >= 1, `dragging the right edge sets how long it stays (${hold} s)`)
  const wBefore = (await p.locator('[data-drawing-block]').first().boundingBox()).width
  await p.getByLabel('Çizimin süresi (sn)').fill('40'); await p.waitForTimeout(200)
  const wAfter = (await p.locator('[data-drawing-block]').first().boundingBox()).width
  assert(wAfter > wBefore * 1.5, `typing a duration changes the block width too (${Math.round(wBefore)} → ${Math.round(wAfter)}px)`)
  await p.getByLabel('Çizimin başlangıç zamanı').fill('0:30.00'); await p.getByLabel('Çizimin başlangıç zamanı').press('Enter'); await p.waitForTimeout(200)
  assert(/00:30|0:30/.test(await p.getByTestId('drawing-status').innerText()), 'typing a start time moves it')
  await p.screenshot({ path: `${SP}/timeline-drawings.png` })

  console.log('4. Numbers are readable and centred')
  await p.evaluate(() => { document.querySelector('video').currentTime = 40 }); await p.waitForTimeout(300)
  const cb = await p.locator('g[data-shape="number"] circle').first().boundingBox()
  assert(cb.width >= 22, `the number badge is ${Math.round(cb.width)}px wide on screen`)
  const tbx = await p.locator('g[data-shape="number"] text').first().boundingBox()
  assert(Math.abs((tbx.x + tbx.width / 2) - (cb.x + cb.width / 2)) < 3 && Math.abs((tbx.y + tbx.height / 2) - (cb.y + cb.height / 2)) < 5, 'the digit is centred in the badge')

  console.log('3. Light sweeps from the top')
  await p.evaluate(() => { document.querySelector('video').currentTime = 60 }); await p.waitForTimeout(300)
  await tool('Aydınlat'); await p.mouse.click(X(0.5), Y(0.5))
  const front = async () => +(await p.locator('g[data-shape="spot"] linearGradient stop').nth(2).getAttribute('offset'))
  const f0 = await front()
  for (let i = 0; i < 40; i++) await p.keyboard.press('ArrowRight')
  await p.waitForTimeout(300)
  const f1 = await front()
  assert(f1 > f0 + 0.1, `the light front travels down over time (${f0.toFixed(2)} → ${f1.toFixed(2)})`)

  console.log('2. Close-up window can be moved')
  await p.evaluate(() => { document.querySelector('video').currentTime = 80 }); await p.waitForTimeout(300)
  await tool('Zoom'); await p.mouse.click(X(0.6), Y(0.5))
  const before = await p.locator('canvas[data-zoom-inset]').boundingBox()
  const mv = await p.locator('[data-zoom-move]').boundingBox()
  await drag(mv.x + mv.width / 2, mv.y + mv.height / 2, mv.x + mv.width / 2 + 120, mv.y + mv.height / 2 + 60)
  const after = await p.locator('canvas[data-zoom-inset]').boundingBox()
  assert(after.x > before.x + 60 && after.y > before.y + 20, `dragging its label moves the close-up (${Math.round(before.x)},${Math.round(before.y)} → ${Math.round(after.x)},${Math.round(after.y)})`)
  assert(Math.abs(after.width - before.width) < 2, 'the size is unchanged by moving')
  assert(await p.locator('g[data-shape="zoom"]').count() === 1, 'no extra shape was made')

  console.log('5. Right click stops what is going on')
  await p.evaluate(() => { document.querySelector('video').currentTime = 100 }); await p.waitForTimeout(300)
  await p.keyboard.press('Space'); await p.waitForTimeout(400)
  assert(await p.evaluate(() => !document.querySelector('video').paused), 'video is playing')
  await p.mouse.click(X(0.5), Y(0.5), { button: 'right' }); await p.waitForTimeout(300)
  assert(await p.evaluate(() => document.querySelector('video').paused), 'a right click pauses playback')
  await tool('Çizgi')
  const n0 = await p.locator('g[data-shape]').count()
  await p.mouse.move(X(0.2), Y(0.3)); await p.mouse.down(); await p.mouse.move(X(0.5), Y(0.3), { steps: 4 })
  await p.mouse.click(X(0.8), Y(0.8), { button: 'right' }); await p.mouse.up(); await p.waitForTimeout(200)
  assert(await p.locator('g[data-shape]').count() === n0, 'a right click in the middle of drawing cancels that drawing')
  assert((await tb.getByRole('button', { name: 'Seç', exact: true }).getAttribute('aria-pressed')) === 'true', 'and returns to the Seç tool')
  await p.mouse.click(X(0.7), Y(0.5)) // select something (number)
  await p.mouse.click(X(0.5), Y(0.9), { button: 'right' }); await p.waitForTimeout(150)
  assert(await p.locator('g[data-selected]').count() === 0, 'a right click clears the selection')

  console.log('errors:', JSON.stringify(errs)); assert(errs.length === 0, 'no console errors')
  await b.close()
})().catch(e => { console.error('E2E FAIL', e.message); process.exit(1) })

// Browser-level check for ScoutDesk. Needs: `npm i -g playwright && npx playwright install chromium`,
// the app running on http://localhost:4000 (`npm run build && npm start`) and a freshly seeded DB
// (`SEED_VIDEO_FORMAT=webm npm run seed:reset` if your Chromium build lacks H.264).
const { chromium } = require('playwright')
const fs = require('fs')
const SP = process.argv[2] || './e2e-out'
require('fs').mkdirSync(SP, { recursive: true })
const API = 'http://localhost:4000/api'
const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); console.log('  ok -', m) }
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true })
  const p = await ctx.newPage()
  const errs = []
  p.on('console', m => m.type() === 'error' && errs.push(m.text()))
  p.on('pageerror', e => errs.push('PAGEERROR ' + e.message))
  await p.goto('http://localhost:4000/match/m_demo', { waitUntil: 'networkidle' })
  await p.waitForFunction(() => { const v = document.querySelector('video'); return v && v.readyState >= 2 })
  const vt = () => p.evaluate(() => document.querySelector('video').currentTime)
  const clips = async () => (await (await p.request.get(`${API}/clips?matchId=m_demo`)).json())
  const rowsInDom = async () => Number(await p.locator('[role=table]').getAttribute('aria-rowcount'))
  const domRows = () => p.locator('[role=row][data-clip-id]').count()
  const rowText = () => p.locator('[role=row][data-clip-id]').allInnerTexts()

  console.log('Drawing + screenshot')
  await p.evaluate(() => { document.querySelector('video').currentTime = 78.2 }); await p.waitForTimeout(400)
  const tb = p.getByRole('toolbar', { name: 'Frame tools' })
  const stage = await p.locator('svg[aria-label="Drawing overlay"]').boundingBox()
  const shapesN = () => p.locator('svg[aria-label="Drawing overlay"] g[data-shape]').count()
  await tb.getByRole('button', { name: 'Arrow' }).click()
  await p.mouse.move(stage.x + 100, stage.y + 100); await p.mouse.down(); await p.mouse.move(stage.x + 300, stage.y + 160, { steps: 6 }); await p.mouse.up()
  await tb.getByRole('button', { name: 'Circle' }).click()
  await p.mouse.move(stage.x + 400, stage.y + 150); await p.mouse.down(); await p.mouse.move(stage.x + 450, stage.y + 200, { steps: 4 }); await p.mouse.up()
  assert(await shapesN() === 2, 'arrow + circle drawn on the paused frame')
  await p.screenshot({ path: `${SP}/p3-drawing.png` })
  const dl = p.waitForEvent('download')
  await tb.getByRole('button', { name: 'Screenshot' }).click()
  const d = await dl
  await d.saveAs(`${SP}/snapshot.png`)
  assert(fs.statSync(`${SP}/snapshot.png`).size > 20000, `screenshot PNG downloaded (${d.suggestedFilename()}, ${fs.statSync(`${SP}/snapshot.png`).size} bytes)`)
  await p.keyboard.press('ArrowRight'); await p.waitForTimeout(150)
  assert(await shapesN() === 0, 'drawings hide when stepping to another frame')
  await p.keyboard.press('ArrowLeft'); await p.waitForTimeout(150)
  assert(await shapesN() === 2, 'and reappear when returning to that frame')
  await p.keyboard.press('Control+z'); await p.waitForTimeout(100)
  assert(await shapesN() === 1, 'Ctrl+Z undoes the last shape only')

  console.log('Zoom')
  const pitch = await p.locator('video').boundingBox()
  await p.mouse.move(pitch.x + pitch.width / 2, pitch.y + pitch.height / 2)
  await p.mouse.wheel(0, -300); await p.waitForTimeout(150)
  const z = await tb.getByRole('button', { name: /Reset zoom/ }).innerText()
  assert(parseFloat(z) > 1, 'wheel zooms the video (' + z + ')')
  await tb.getByRole('button', { name: /Reset zoom/ }).click()
  assert(parseFloat(await tb.getByRole('button', { name: /Reset zoom/ }).innerText()) === 1, 'reset zoom')

  console.log('Clip table: select, sort, filter')
  assert(await rowsInDom() === 30, '30 rows initially'); assert(await domRows() < 30, `virtualized: only ${await domRows()} of 30 rows are in the DOM`)
  await p.locator('[role=row][data-clip-id]').nth(2).click()
  await p.waitForTimeout(300)
  const sel = await clips().then(cs => cs.sort((a, b) => a.timeSec - b.timeSec)[2])
  assert(Math.abs((await vt()) - sel.startSec) < 0.1, `clicking row 3 seeks to its start (${sel.startSec}s)`)
  await p.getByRole('columnheader', { name: 'Outcome' }).click()
  const first = (await rowText())[0]
  assert(/Success/.test(first), 'sort by outcome puts Success first')
  await p.getByRole('columnheader', { name: 'Outcome' }).click()
  assert(/Fail/.test((await rowText())[0]), 'second click reverses (Fail first)')
  await p.getByLabel('Search clips').fill('goal')
  await p.waitForTimeout(200)
  assert(await rowsInDom() === 5 || await rowsInDom() > 0, `text filter "goal" -> ${await rowsInDom()} rows`)
  const goalRows = await rowsInDom()
  await p.getByLabel('Search clips').fill('')
  await p.getByRole('button', { name: /Filter by Player/ }).click()
  await p.getByRole('listbox', { name: 'Player' }).getByRole('option', { name: 'Marcus Hale' }).click()
  await p.keyboard.press('Escape')
  const hale = await rowsInDom()
  const haleExpected = (await clips()).filter(c => c.playerId === 'p_hale').length
  assert(hale === haleExpected, `player filter Marcus Hale -> ${hale} rows (expected ${haleExpected})`)
  await p.getByRole('button', { name: /Filter by Outcome/ }).click()
  await p.getByRole('listbox', { name: 'Outcome' }).getByRole('option', { name: 'Success' }).click()
  await p.keyboard.press('Escape')
  assert(await rowsInDom() === (await clips()).filter(c => c.playerId === 'p_hale' && c.outcome === 'success').length, 'filters AND together (player + outcome)')
  // timeline reflects filter
  const countTxt = await p.getByText(/clips$/).first().innerText()
  console.log('  header:', countTxt)
  // preset
  await p.getByRole('button', { name: 'Filter presets' }).click()
  await p.getByRole('menuitem', { name: 'Save current filters…' }).click()
  await p.getByLabel('Preset name').fill('Hale successes')
  await p.getByRole('button', { name: 'Save', exact: true }).click()
  await p.keyboard.press('Escape')
  await p.getByRole('button', { name: /Clear \(/ }).click()
  assert(await rowsInDom() === 30, 'clear filters restores all 30')
  await p.getByRole('button', { name: 'Filter presets' }).click()
  await p.getByRole('menuitem', { name: 'Hale successes' }).click()
  assert(await rowsInDom() < 30, 'preset re-applies the saved filter combination')
  await p.getByRole('button', { name: /Clear \(/ }).click()

  console.log('Multi-select + bulk')
  const created = []
  const rows = p.locator('[role=row][data-clip-id]')
  await p.getByRole('columnheader', { name: 'Time' }).click()
  await p.evaluate(() => { document.querySelector('[role=table]')?.parentElement && [...document.querySelectorAll('*')].filter(e => e.scrollTop > 0 && e.contains(document.querySelector('[role=row][data-clip-id]'))).forEach(e => { e.scrollTop = 0 }) })
  await rows.nth(0).click()
  await rows.nth(3).click({ modifiers: ['Shift'] })
  assert((await p.getByText('4 selected').count()) === 1, 'shift-click selects a range of 4')
  await rows.nth(6).click({ modifiers: ['Control'] })
  assert((await p.getByText('5 selected').count()) === 1, 'ctrl-click adds one more')
  const ids = await p.locator('[role=row][aria-selected=true]').evaluateAll(els => els.map(e => e.dataset.clipId))
  await p.getByRole('button', { name: 'Set outcome to fail' }).click(); await p.waitForTimeout(500)
  let all = await clips()
  assert(ids.every(id => all.find(c => c.id === id).outcome === 'fail'), 'bulk outcome -> fail applied on the server to all 5')
  await p.keyboard.press('Control+z'); await p.waitForTimeout(500)
  all = await clips()
  assert(ids.some(id => all.find(c => c.id === id).outcome !== 'fail'), 'one Ctrl+Z reverts the whole bulk edit')
  await p.getByRole('button', { name: 'Add label' }).first().click()
  await p.getByLabel('Label to add').fill('Review Me'); await p.keyboard.press('Enter'); await p.waitForTimeout(500)
  all = await clips()
  assert(ids.every(id => all.find(c => c.id === id).labels.includes('review-me')), 'bulk add label (normalised to review-me)')
  await p.keyboard.press('Escape')
  await p.keyboard.press('Control+z'); await p.waitForTimeout(400)
  // delete + undo
  await p.keyboard.press('Delete'); await p.waitForTimeout(500)
  assert((await clips()).length === 25, 'Delete key removes the 5 selected clips')
  await p.keyboard.press('Control+z'); await p.waitForTimeout(600)
  assert((await clips()).length === 30, 'undo restores them (same ids)')

  console.log('Inspector + timeline edge drag')
  if (await p.getByRole('button', { name: 'Clear selection' }).count()) await p.getByRole('button', { name: 'Clear selection' }).click()
  await rows.nth(10).click()
  await p.keyboard.press('Enter')
  await p.getByRole('tab', { name: 'Clip', exact: true }).waitFor()
  const active = (await clips()).sort((a, b) => a.timeSec - b.timeSec)[10]
  await p.getByLabel('Start time').click()
  const startBefore = active.startSec
  await p.getByRole('button', { name: 'Start minus half a second' }).click(); await p.waitForTimeout(500)
  let c10 = (await clips()).find(c => c.id === active.id)
  assert(Math.abs(c10.startSec - (startBefore - 0.5)) < 0.05, `inspector −0.5s moved start ${startBefore} -> ${c10.startSec}`)
  await p.getByLabel('Notes').first().fill('Edited via inspector'); await p.getByLabel('Notes').first().blur(); await p.waitForTimeout(500)
  c10 = (await clips()).find(c => c.id === active.id)
  assert(c10.notes === 'Edited via inspector', 'notes saved on blur')
  await p.screenshot({ path: `${SP}/p4-inspector.png` })

  // drag the end edge of the selected clip on the timeline
  const box = await p.getByTestId('timeline-canvas').boundingBox()
  const W = box.width - 104
  const xEnd = box.x + 104 + (c10.endSec / 180) * W
  const laneY = box.y + 22 + 48 + 5 + 8 // first lane centre (lane index per category computed below)
  const cats = await (await p.request.get(`${API}/taxonomy`)).json()
  const lane = cats.findIndex(c => c.tagTypes.some(t => t.id === c10.tagTypeId))
  const laneH = await p.evaluate(() => 0)
  const laneH2 = Math.min(26, Math.max(12, Math.floor((box.height + 26 - 26 - 20 - 38 - 22 - 16) / cats.length) - 3)) // mirrors Timeline.tsx lane sizing
  const y = box.y + 20 + 38 + 4 + lane * (laneH2 + 3) + laneH2 / 2
  await p.mouse.move(xEnd - 1, y); await p.mouse.down(); await p.mouse.move(xEnd + 45, y, { steps: 6 }); await p.mouse.up(); await p.waitForTimeout(600)
  const after = (await clips()).find(c => c.id === active.id)
  console.log(`  end ${c10.endSec} -> ${after.endSec} (lane ${lane})`)
  assert(after.endSec > c10.endSec + 2, 'dragging the clip end edge on the timeline extends it (server updated)')
  await p.keyboard.press('Control+z'); await p.waitForTimeout(500)
  assert(Math.abs((await clips()).find(c => c.id === active.id).endSec - c10.endSec) < 0.05, 'the whole drag undoes in one step')

  console.log('Cheat sheet')
  await p.keyboard.press('Escape')
  await p.keyboard.press('?')
  await p.getByRole('dialog', { name: 'Keyboard shortcuts' }).waitFor()
  await p.screenshot({ path: `${SP}/p10-cheatsheet.png` })
  const sheet = await p.getByRole('dialog').innerText()
  assert(/Play \/ pause/.test(sheet) && /Tag: Shot/.test(sheet) && /Undo/.test(sheet), 'cheat sheet lists transport, tag and edit shortcuts')
  await p.keyboard.press('Escape')

  console.log('Event log')
  await p.getByRole('tab', { name: 'Event log' }).click()
  await p.evaluate(() => { document.querySelector('video').currentTime = 80 }); await p.waitForTimeout(500)
  const cur = await p.locator('[aria-current=true]').first().innerText()
  console.log('  active event at 80s:', cur.replace(/\n+/g, ' | '))
  assert(/Goal/.test(cur), 'event log highlights the latest event at/before the playhead (Goal @78.2s)')
  await p.screenshot({ path: `${SP}/p4-eventlog.png` })

  console.log('Errors:', JSON.stringify(errs))
  assert(errs.length === 0, 'no console errors')
  await b.close()
})().catch(e => { console.error('E2E FAIL', e.message); process.exit(1) })

// Phase 7/9: playlists (drag/drop, reorder, fade), continuous playback, FFmpeg export via the tray, and public share links.
const { chromium } = require('playwright')
const SP = process.argv[2] || './e2e-out'
const API = 'http://localhost:4000/api'
require('fs').mkdirSync(SP, { recursive: true })
const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); console.log('  ok -', m) }
const H = { 'x-user-id': 'u_admin' } // (no content-type: Fastify rejects JSON-typed requests with empty bodies)
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true })
  const p = await ctx.newPage()
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()))
  p.on('dialog', d => d.accept(d.type() === 'prompt' ? 'E2E Highlights' : undefined))
  // cleanup leftovers
  for (const x of await (await fetch(`${API}/playlists`)).json()) if (x.title.startsWith('E2E')) await fetch(`${API}/playlists/${x.id}`, { method: 'DELETE', headers: H })

  console.log('Create + fill playlist')
  await p.goto('http://localhost:4000/playlists', { waitUntil: 'networkidle' })
  assert(await p.getByText(/Build your first playlist|Select a playlist/).count() === 1, 'empty state shown')
  await p.getByRole('button', { name: /New playlist/ }).first().click()
  await p.getByLabel('Playlist title').waitFor()
  assert((await p.getByLabel('Playlist title').inputValue()) === 'E2E Highlights', 'playlist created and opened')
  const lib = p.getByRole('complementary', { name: 'Clip library panel' })
  await lib.getByLabel('Search clip library').fill('goal')
  await p.waitForTimeout(300)
  const rows = lib.getByRole('listitem')
  assert(await rows.count() >= 3, 'library search filters clips (' + await rows.count() + ' match "goal" in tag, notes or labels)')
  // drag the first row into the list (HTML5 DnD)
  await rows.first().dragTo(p.getByRole('region', { name: 'Playlist items' }))
  await p.waitForTimeout(800)
  let pl = (await (await fetch(`${API}/playlists`)).json()).find(x => x.title === 'E2E Highlights')
  assert(pl.itemCount === 1, 'dragging a clip from the library adds it (server has 1 item)')
  // add 2 more with the + button
  await rows.nth(1).getByRole('button', { name: 'Add to playlist' }).click()
  await rows.nth(2).getByRole('button', { name: 'Add to playlist' }).click()
  await p.waitForTimeout(900)
  pl = (await (await fetch(`${API}/playlists`)).json()).find(x => x.title === 'E2E Highlights')
  assert(pl.itemCount === 3, 'the + buttons add more (3 items)')

  console.log('Edit: title, reorder, transition')
  await p.getByLabel('Title for clip 1').fill('Opening goal')
  await p.getByLabel('Title for clip 1').blur()
  await p.getByRole('button', { name: 'Move clip 3 up' }).click({ force: true })
  await p.getByRole('button', { name: /Transition into clip 2/ }).click()
  await p.waitForTimeout(900)
  const full = await (await fetch(`${API}/playlists/${pl.id}`)).json()
  assert(full.items[0].title === 'Opening goal', 'custom title saved')
  assert(full.items[1].transition === 'fade', 'fade transition saved on item 2')
  const times = full.items.map(i => i.clip.timeSec)
  assert(new Set(times).size === 3, 'three distinct clips after reorder: ' + times.join(', '))
  await p.screenshot({ path: `${SP}/p7-playlist.png` })

  console.log('Continuous playback')
  await p.getByRole('button', { name: 'Play', exact: true }).click()
  await p.waitForFunction(() => { const v = document.querySelector('video[aria-label="Playlist video"]'); return v && !v.paused && v.currentTime > 0 }, null, { timeout: 15000 })
  assert(await p.getByText('Opening goal').count() >= 1, 'title overlay / list shows the clip title')
  const first = full.items[0].clip
  // jump near the end of clip 1 and verify auto-advance to clip 2
  await p.evaluate((t) => { document.querySelector('video[aria-label="Playlist video"]').currentTime = t }, first.endSec - 0.6)
  await p.waitForFunction((end) => { const v = document.querySelector('video[aria-label="Playlist video"]'); return v.currentTime > 0 && (v.currentTime < end - 3 || v.currentTime > end + 0.5) && document.querySelector('[aria-current=true]') }, first.endSec, { timeout: 10000 })
  await p.waitForTimeout(600)
  const cur = await p.locator('li [aria-current=true]').first().innerText().catch(() => '')
  const idx = await p.getByText(/^\d+ \/ 3$/).first().innerText()
  assert(/^2 \/ 3$/.test(idx.replace(/\s+/g, ' ').trim()), `auto-advanced to clip 2 (counter reads "${idx.trim()}")`)
  await p.keyboard.press('Space')

  console.log('Export through the queue')
  await p.getByRole('button', { name: 'Export MP4' }).click()
  const tray = p.getByRole('region', { name: 'Exports' })
  await tray.waitFor()
  await tray.getByRole('progressbar').waitFor({ timeout: 5000 }).catch(() => {})
  const link = tray.getByRole('link', { name: /Download MP4/ })
  await link.waitFor({ timeout: 120000 })
  await p.screenshot({ path: `${SP}/p7-export-done.png` })
  const href = await link.getAttribute('href')
  const dl = await ctx.request.get('http://localhost:4000' + href)
  const body = await dl.body()
  assert(dl.ok() && body.length > 100000 && body.subarray(4, 8).toString() === 'ftyp', `download is a real MP4 (${(body.length / 1024).toFixed(0)} KB)`)

  console.log('Share link (anonymous context)')
  await p.getByRole('button', { name: 'Share', exact: true }).click()
  await p.getByLabel('Password (optional)').fill('pitchside')
  await p.getByRole('button', { name: 'Create link' }).click()
  await p.getByText('Link created and copied').waitFor()
  const shares = await (await fetch(`${API}/shares?kind=playlist&refId=${pl.id}`, { headers: H })).json()
  assert(shares.length === 1 && shares[0].hasPassword, 'link stored with password flag')
  const anon = await b.newContext({ viewport: { width: 1280, height: 800 } })
  const a = await anon.newPage()
  const aerrs = []; a.on('pageerror', e => aerrs.push(e.message))
  await a.goto(`http://localhost:4000/s/${shares[0].token}`)
  await a.getByLabel('Password').waitFor()
  assert(await a.getByText('ScoutDesk').count() >= 1 && await a.getByRole('navigation', { name: 'Primary' }).count() === 0, 'public page has no app sidebar / navigation')
  await a.getByLabel('Password').fill('wrong'); await a.getByRole('button', { name: 'Open' }).click()
  await a.getByRole('alert').waitFor()
  assert(/Wrong password/.test(await a.getByRole('alert').innerText()), 'wrong password is rejected')
  await a.getByLabel('Password').fill('pitchside'); await a.getByRole('button', { name: 'Open' }).click()
  await a.getByRole('navigation', { name: /x/ }).count()
  await a.getByRole('complementary', { name: 'Clips in this playlist' }).waitFor()
  assert(await a.getByRole('complementary', { name: 'Clips in this playlist' }).getByRole('listitem').count() === 3, 'shared playlist shows its 3 clips')
  await a.getByRole('button', { name: 'Play', exact: true }).click()
  await a.waitForFunction(() => { const v = document.querySelector('video'); return v && !v.paused && v.currentTime > 0 }, null, { timeout: 15000 })
  assert(true, 'shared playlist plays for an anonymous viewer (signed stream URL)')
  await a.screenshot({ path: `${SP}/p9-share.png` })
  assert(aerrs.length === 0, 'no errors on the public page')
  // expired
  await fetch(`${API}/shares/${shares[0].id}`, { method: 'DELETE', headers: H })
  await a.reload()
  await a.getByText('This link is no longer available').waitFor()
  assert(true, 'revoked link shows a friendly message')
  await anon.close()

  // cleanup
  for (const x of await (await fetch(`${API}/exports`)).json()) if (x.label === 'E2E Highlights') await fetch(`${API}/exports/${x.id}`, { method: 'DELETE', headers: H })
  await fetch(`${API}/playlists/${pl.id}`, { method: 'DELETE', headers: H })
  console.log('errors:', JSON.stringify(errs))
  assert(errs.length === 0, 'no console errors')
  await b.close()
})().catch(e => { console.error('E2E FAIL', e.message); process.exit(1) })

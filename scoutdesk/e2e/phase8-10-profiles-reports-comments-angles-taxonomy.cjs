// Phases 8-10: profile, compare, reports + snapshots, comments, multi-angle sync, taxonomy editor, viewer limits.
const { chromium } = require('playwright')
const { execFileSync } = require('child_process')
const fs = require('fs')
const SP = process.argv[2] || './e2e-out'
const API = 'http://localhost:4000/api'
fs.mkdirSync(SP, { recursive: true })
const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); console.log('  ok -', m) }
const H = { 'x-user-id': 'u_admin' }
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true })
  const p = await ctx.newPage()
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()))
  p.on('dialog', d => d.accept())
  const getJson = async (u) => (await fetch(API + u, { headers: H })).json()

  // leftovers from aborted runs
  for (const c of await getJson('/clips?matchId=m_demo')) for (const cm of await getJson('/comments?clipId=' + c.id)) if (cm.body.startsWith('E2E')) await fetch(`${API}/comments/${cm.id}`, { method: 'DELETE', headers: H })
  console.log('Player profile')
  await p.goto('http://localhost:4000/players', { waitUntil: 'networkidle' })
  await p.getByRole('link', { name: 'Marcus Hale' }).click()
  await p.getByRole('heading', { name: 'Marcus Hale' }).waitFor()
  const goals = await p.locator('dt:has-text("Goals") + dd').innerText()
  assert(goals.trim().startsWith('2'), 'profile shows 2 goals from tags')
  assert(await p.getByRole('img', { name: /Marcus Hale heatmap: 7 located actions/ }).count() === 1, 'heatmap plots the 7 located actions')
  assert(await p.getByRole('img', { name: /Radar chart of Marcus Hale/ }).count() === 1, 'radar chart rendered with accessible description')
  await p.getByRole('radio', { name: 'Events' }).click()
  await p.screenshot({ path: `${SP}/p8-profile.png`, fullPage: false })
  await p.locator('a.timecode').first().click()
  await p.waitForURL(/\/match\/m_demo/)
  await p.waitForFunction(() => document.querySelector('video')?.readyState >= 2)
  await p.waitForTimeout(500)
  assert((await p.locator('[role=row][aria-selected=true]').count()) === 1, 'clip link opens the match with that clip selected')

  console.log('Compare')
  await p.goto('http://localhost:4000/players/compare?a=p_hale&b=p_ferreira', { waitUntil: 'networkidle' })
  await p.getByRole('table').waitFor()
  assert(await p.getByRole('table').getByText('▲').count() >= 3, 'leader markers shown in the comparison table')
  assert(await p.getByRole('img', { name: /Radar comparison/ }).count() === 1, 'overlay radar rendered')
  await p.screenshot({ path: `${SP}/p8-compare.png` })
  await p.goto('http://localhost:4000/players', { waitUntil: 'networkidle' })
  await p.getByLabel('Select Marcus Hale to compare').check(); await p.getByLabel('Select Kofi Mensah to compare').check()
  await p.getByRole('button', { name: /Compare \(2\/2\)/ }).click()
  await p.waitForURL(/compare\?a=p_hale&b=p_mensah/)
  assert(true, 'Players page "Compare" opens the two ticked players')

  console.log('Snapshot → report library')
  await p.goto('http://localhost:4000/match/m_demo', { waitUntil: 'networkidle' })
  await p.waitForFunction(() => document.querySelector('video')?.readyState >= 2)
  await p.evaluate(() => { document.querySelector('video').currentTime = 78.2 }); await p.waitForTimeout(400)
  await p.keyboard.press('d')
  const box = await p.locator('svg[aria-label="Drawing overlay"]').boundingBox()
  await p.mouse.move(box.x + 120, box.y + 120); await p.mouse.down(); await p.mouse.move(box.x + 300, box.y + 180, { steps: 5 }); await p.mouse.up()
  await p.keyboard.press('Escape')
  await p.getByRole('button', { name: 'Snapshot' }).click()
  await p.getByRole('menuitem', { name: 'Save to report library' }).click()
  await p.getByText(/Saved to the report library/).waitFor()
  const snaps = await getJson('/snapshots?matchId=m_demo')
  assert(snaps.length >= 1 && Math.abs(snaps[0].timeSec - 78.2) < 0.2, 'snapshot stored on the server with its match + time')

  console.log('Reports')
  await p.goto('http://localhost:4000/reports?type=player&id=p_hale', { waitUntil: 'networkidle' })
  await p.getByRole('button', { name: /Include snapshot at 1:18/ }).first().click()
  await p.getByLabel('Written notes').fill('E2E: strong runner, finishes first time.')
  await p.getByRole('button', { name: 'Generate PDF' }).click()
  const frame = p.locator('iframe[title="Report preview"]')
  await frame.waitFor({ timeout: 30000 })
  const src = await frame.getAttribute('src')
  const head = await p.evaluate(async (u) => { const r = await fetch(u); const b = new Uint8Array(await r.arrayBuffer()); return { magic: String.fromCharCode(...b.slice(0, 5)), size: b.length } }, src)
  assert(head.magic === '%PDF-' && head.size > 15000, `preview is a real PDF with the snapshot embedded (${head.size} bytes)`)
  const dl = p.waitForEvent('download'); await p.getByRole('link', { name: /Download PDF/ }).click(); const d = await dl
  await d.saveAs(`${SP}/hale-report.pdf`)
  assert(/Marcus_Hale/.test(d.suggestedFilename()), 'download filename is ' + d.suggestedFilename())
  await p.getByRole('radio', { name: 'Team report' }).click()
  await p.getByRole('button', { name: 'Generate PDF' }).click()
  await frame.waitFor(); assert(true, 'team report generates too')
  await p.screenshot({ path: `${SP}/p9-reports.png` })
  for (const s of snaps) await fetch(`${API}/snapshots/${s.id}`, { method: 'DELETE', headers: H })

  console.log('Comments')
  await p.goto('http://localhost:4000/match/m_demo', { waitUntil: 'networkidle' })
  await p.waitForFunction(() => document.querySelector('video')?.readyState >= 2)
  await p.locator('[role=row][data-clip-id]').nth(2).click()
  await p.keyboard.press('Enter')
  const box2 = p.getByRole('region', { name: 'Comments' })
  await box2.getByLabel('Write a comment').fill('E2E first touch, compare with @0:24 duel')
  await box2.getByRole('button', { name: 'Comment', exact: true }).click()
  await box2.locator('p', { hasText: 'E2E first touch' }).waitFor()
  await box2.getByRole('button', { name: 'Reply' }).first().click()
  await box2.getByLabel('Write a comment').fill('E2E agreed')
  await box2.getByRole('button', { name: 'Reply', exact: true }).last().click()
  await box2.locator('p', { hasText: 'E2E agreed' }).waitFor()
  const chip = box2.getByRole('button', { name: /Jump to 0:24/ })
  await chip.click(); await p.waitForTimeout(400)
  assert(Math.abs((await p.evaluate(() => document.querySelector('video').currentTime)) - 24) < 0.5, '@0:24 mention seeks the video to 24s')
  assert(await box2.locator('p', { hasText: 'E2E agreed' }).count() === 1, 'reply threads under the comment')
  await p.screenshot({ path: `${SP}/p10-comments.png` })
  await box2.getByRole('button', { name: 'Delete comment' }).first().click(); await p.waitForTimeout(400)
  assert(await box2.locator('p', { hasText: 'E2E first touch' }).count() === 0, 'deleting a parent removes its replies')

  console.log('Multi-angle sync')
  execFileSync('ffmpeg', ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=s=320x180:r=25:d=8', '-c:v', 'libvpx', '-b:v', '200k', `${SP}/angle2.webm`])
  const form = new FormData(); form.append('title', 'E2E tactical cam'); form.append('matchId', 'm_demo'); form.append('angle', 'Tactical'); form.append('file', new Blob([fs.readFileSync(`${SP}/angle2.webm`)]), 'angle2.webm')
  const up = await (await fetch(API + '/videos', { method: 'POST', headers: H, body: form })).json()
  for (let i = 0; i < 30; i++) { if ((await getJson('/videos/' + up.id)).status === 'ready') break; await new Promise(r => setTimeout(r, 300)) }
  await p.reload({ waitUntil: 'networkidle' })
  await p.waitForFunction(() => document.querySelector('video')?.readyState >= 2)
  await p.getByRole('button', { name: 'Camera angles' }).click()
  await p.getByRole('menuitem', { name: 'Tactical' }).last().click()
  const sec = p.getByLabel('Second angle: Tactical').locator('video')
  await sec.waitFor()
  await p.waitForFunction(() => document.querySelectorAll('video').length === 2 && document.querySelectorAll('video')[1].readyState >= 2)
  await p.evaluate(() => { document.querySelectorAll('video')[0].currentTime = 5 }); await p.waitForTimeout(500)
  const t2 = () => p.evaluate(() => document.querySelectorAll('video')[1].currentTime)
  assert(Math.abs(await t2() - 5) < 0.2, `secondary follows main seeks (main 5.0 → secondary ${(await t2()).toFixed(2)})`)
  await p.getByLabel('Sync offset in seconds').fill('2'); await p.waitForTimeout(500)
  assert(Math.abs(await t2() - 7) < 0.25, `offset +2s applied live (secondary ${(await t2()).toFixed(2)})`)
  await p.getByRole('group', { name: 'Sync offset' }).getByRole('button', { name: 'Save', exact: true }).click(); await p.waitForTimeout(500)
  assert(Math.abs((await getJson('/videos/' + up.id)).syncOffset - 2) < 0.01, 'offset persisted on the video')
  await p.evaluate(() => { document.querySelectorAll('video')[0].currentTime = 1 }); await p.waitForTimeout(400)
  await p.keyboard.press('Space'); await p.waitForTimeout(1500); await p.keyboard.press('Space')
  const dm = await p.evaluate(() => [document.querySelectorAll('video')[0].currentTime, document.querySelectorAll('video')[1].currentTime])
  assert(Math.abs((dm[1] - dm[0]) - 2) < 0.5, `stay in sync while playing (Δ=${(dm[1] - dm[0]).toFixed(2)}s)`)
  await p.screenshot({ path: `${SP}/p10-angles.png` })
  await fetch(`${API}/videos/${up.id}`, { method: 'DELETE', headers: H })

  console.log('Taxonomy editor')
  await p.evaluate(() => localStorage.setItem('scoutdesk.app', JSON.stringify({ state: { theme: 'dark', userId: 'u_admin' }, version: 0 })))
  await p.goto('http://localhost:4000/settings', { waitUntil: 'networkidle' })
  await p.getByLabel('New category name').fill('E2E Cat'); await p.getByRole('button', { name: 'Add category' }).click()
  const card = p.getByRole('region', { name: 'Category E2E Cat' })
  await card.waitFor()
  await card.getByLabel('New tag in E2E Cat').fill('E2E Tag'); await card.getByRole('button', { name: 'Add tag' }).click()
  await card.getByLabel('Tag name (E2E Tag)').waitFor()
  await card.getByRole('button', { name: 'Set hotkey' }).click(); await p.keyboard.press('f')
  await p.getByText(/reserved for playback/).waitFor()
  assert(true, 'reserved key F is rejected in the editor')
  await p.keyboard.press('x')
  await card.getByRole('button', { name: /Hotkey X/ }).waitFor()
  assert((await getJson('/taxonomy')).flatMap(c => c.tagTypes).find(t => t.name === 'E2E Tag').hotkey === 'x', 'hotkey X saved')
  await card.getByRole('button', { name: /Hotkey X/ }).click(); await p.keyboard.press('s')
  await p.getByText(/already used by "Shot"/).waitFor()
  assert(true, 'duplicate hotkey is refused by the server with a clear message')
  await p.keyboard.press('Escape')
  await p.screenshot({ path: `${SP}/p10-taxonomy.png` })
  await p.goto('http://localhost:4000/match/m_demo', { waitUntil: 'networkidle' })
  await p.waitForFunction(() => document.querySelector('video')?.readyState >= 2)
  assert(await p.getByRole('region', { name: 'E2E Cat' }).count() === 1, 'new category appears in the tagging panel')
  const before = (await getJson('/clips?matchId=m_demo')).length
  await p.evaluate(() => { document.querySelector('video').currentTime = 60 }); await p.waitForTimeout(300)
  await p.keyboard.press('x'); await p.waitForTimeout(500)
  assert((await getJson('/clips?matchId=m_demo')).length === before + 1, 'the new hotkey X tags immediately')
  for (const c of (await getJson('/clips?matchId=m_demo')).filter(c => c.timeSec > 59.5 && c.timeSec < 60.5)) await fetch(`${API}/clips/${c.id}`, { method: 'DELETE', headers: H })
  const tax = await getJson('/taxonomy'); const cat = tax.find(c => c.name === 'E2E Cat')
  for (const t of cat.tagTypes) await fetch(`${API}/tag-types/${t.id}`, { method: 'DELETE', headers: H })
  await fetch(`${API}/categories/${cat.id}`, { method: 'DELETE', headers: H })

  console.log('Viewer limits')
  await p.evaluate(() => localStorage.setItem('scoutdesk.app', JSON.stringify({ state: { theme: 'dark', userId: 'u_viewer' }, version: 0 })))
  await p.goto('http://localhost:4000/settings', { waitUntil: 'networkidle' })
  assert(await p.getByText(/Only admins can edit the taxonomy/).count() === 1, 'viewer cannot edit the taxonomy')
  await p.goto('http://localhost:4000/match/m_demo', { waitUntil: 'networkidle' })
  await p.locator('[role=row][data-clip-id]').nth(2).click(); await p.keyboard.press('Enter')
  assert(await p.getByText('Viewers can read comments but not post.').count() === 1, 'viewer sees comments read-only')

  console.log('errors:', JSON.stringify(errs.filter(e => !/40[13]/.test(e))))
  assert(errs.filter(e => !/40[13]|Failed to load resource/.test(e)).length === 0, 'no console errors')
  await b.close()
})().catch(e => { console.error('E2E FAIL', e.message); process.exit(1) })

// Phase 6: pitch tab, players, teams, match lineups. See e2e/library.cjs for prerequisites.
const { chromium } = require('playwright')
const SP = process.argv[2] || './e2e-out'
const FACE = process.argv[3] || `${SP}/face.png`
const API = 'http://localhost:4000/api'
require('fs').mkdirSync(SP, { recursive: true })
if (!require('fs').existsSync(FACE)) require('fs').writeFileSync(FACE, Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==', 'base64'))
const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); console.log('  ok -', m) }
;(async () => {
  const b = await chromium.launch()
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()))
  p.on('dialog', d => d.accept())
  const players = async () => (await (await p.request.get(`${API}/players`)).json())

  for (const x of (await players()).filter(x => x.name === 'E2E Winger')) await p.request.delete(`${API}/players/${x.id}`, { headers: { 'x-user-id': 'u_admin' } })
  console.log('Players')
  await p.goto('http://localhost:4000/players', { waitUntil: 'networkidle' })
  assert(await p.locator('tbody tr').count() === 3, 'seeded players listed')
  await p.getByLabel('Team', { exact: true }).selectOption({ label: 'Rivermouth United' })
  assert(await p.locator('tbody tr').count() === 1, 'team filter narrows to 1')
  await p.getByLabel('Team', { exact: true }).selectOption('')
  await p.getByRole('button', { name: /New player/ }).click()
  await p.getByLabel('Name', { exact: true }).fill('E2E Winger')
  await p.getByLabel('Jersey', { exact: true }).fill('11')
  await p.getByRole('dialog').getByLabel('Team').selectOption('t_nbfc')
  await p.getByRole('button', { name: 'LW', exact: true }).click()
  await p.getByLabel('Player photo').setInputFiles(FACE)
  await p.getByRole('button', { name: 'Create player' }).click()
  await p.getByText('Player created').waitFor()
  const created = (await players()).find(x => x.name === 'E2E Winger')
  assert(created && created.jersey === 11 && created.positions.join() === 'LW', 'player saved with jersey + position')
  assert(created.photoUrl && (await p.request.get('http://localhost:4000' + created.photoUrl)).ok(), 'photo uploaded and served via signed URL')
  await p.screenshot({ path: `${SP}/p6-players.png` })

  console.log('Teams')
  await p.getByRole('link', { name: 'Teams' }).click()
  await p.getByRole('button', { name: /Rivermouth United/ }).click()
  await p.getByLabel('Formation', { exact: true }).selectOption('4-3-3')
  await p.waitForTimeout(500)
  assert((await (await p.request.get(`${API}/teams`)).json()).find(t => t.id === 't_rmu').formation === '4-3-3', 'formation change persisted')
  await p.getByRole('button', { name: /Northbridge FC/ }).click()
  await p.waitForTimeout(200)
  assert(await p.getByText('E2E Winger').count() >= 1, 'new player is on the Northbridge roster')
  assert(await p.getByText('1W 0D 0L').count() === 1, 'record computed from matches')
  await p.screenshot({ path: `${SP}/p6-teams.png` })

  console.log('Match lineups')
  await p.getByRole('link', { name: 'Matches' }).click()
  await p.getByRole('button', { name: /Edit match/ }).click()
  await p.getByRole('checkbox', { name: /E2E Winger/ }).check()
  await p.getByRole('button', { name: 'Save', exact: true }).click()
  await p.getByText('Match saved').waitFor()
  const m = (await (await p.request.get(`${API}/matches`)).json())[0]
  assert(m.lineups.home.includes(created.id), 'lineup saved on the match')

  console.log('Pitch tab')
  await p.goto('http://localhost:4000/match/m_demo', { waitUntil: 'networkidle' })
  await p.waitForFunction(() => document.querySelector('video')?.readyState >= 2)
  await p.getByRole('tab', { name: 'Pitch' }).click()
  const pitch = p.getByRole('img', { name: /Pitch showing/ })
  assert(/30 events/.test(await pitch.getAttribute('aria-label')), 'all 30 seeded clips plotted')
  await p.screenshot({ path: `${SP}/p6-pitch-events.png` })
  await p.getByRole('radio', { name: 'Heatmap' }).click()
  await p.waitForTimeout(200)
  await p.screenshot({ path: `${SP}/p6-pitch-heat.png` })
  await p.getByRole('radio', { name: 'Events' }).click()
  // filter by player flows into the pitch
  await p.getByRole('tab', { name: 'Clips' }).click()
  await p.getByRole('button', { name: /Filter by Player/ }).click()
  await p.getByRole('listbox', { name: 'Player' }).getByRole('option', { name: 'Marcus Hale' }).click()
  await p.keyboard.press('Escape')
  await p.getByRole('tab', { name: 'Pitch' }).click()
  assert(/7 events/.test(await p.getByRole('img', { name: /Pitch showing/ }).getAttribute('aria-label')), 'player filter applies to the pitch (7 events)')
  await p.getByRole('tab', { name: 'Clips' }).click()
  await p.getByRole('button', { name: /Clear \(/ }).click()
  // place a location for a clip
  await p.evaluate(() => { document.querySelector('video').currentTime = 0 })
  await p.getByRole('tab', { name: 'Clips' }).click()
  await p.locator('[role=row][data-clip-id]').first().click()
  const first = (await (await p.request.get(`${API}/clips?matchId=m_demo`)).json()).sort((a, b) => a.timeSec - b.timeSec)[0]
  await p.getByRole('tab', { name: 'Pitch' }).click()
  await p.getByRole('button', { name: 'Set location' }).click()
  const box = await p.getByRole('img', { name: /Pitch showing/ }).boundingBox()
  const pw = box.height * (109 / 72) // the pitch is letterboxed inside the svg box
  const cx = box.x + box.width / 2, cy = box.y + box.height / 2
  await p.mouse.move(cx - pw * 0.3, cy - box.height * 0.25)
  await p.mouse.down(); await p.mouse.move(cx + pw * 0.3, cy + box.height * 0.25, { steps: 6 }); await p.mouse.up()
  await p.waitForTimeout(500)
  const moved = (await (await p.request.get(`${API}/clips?matchId=m_demo`)).json()).find(c => c.id === first.id)
  console.log(`  clip moved (${first.x},${first.y}) -> (${moved.x},${moved.y}), end (${moved.endX},${moved.endY})`)
  assert(moved.x < 30 && moved.y < 35 && moved.endX > 70 && moved.endY > 65 && moved.zone !== first.zone, 'click-drag sets start + end location on the server')
  await p.keyboard.press('Control+z'); await p.waitForTimeout(500)
  const back = (await (await p.request.get(`${API}/clips?matchId=m_demo`)).json()).find(c => c.id === first.id)
  assert(back.x === first.x && back.endX === first.endX, 'undo restores the original location')

  // cleanup
  await p.request.delete(`${API}/players/${created.id}`, { headers: { 'x-user-id': 'u_admin' } })
  await p.request.patch(`${API}/matches/m_demo`, { headers: { 'x-user-id': 'u_admin' }, data: { lineups: { home: ['p_hale', 'p_ferreira'], away: ['p_mensah'] } } })
  await p.request.patch(`${API}/teams/t_rmu`, { headers: { 'x-user-id': 'u_admin' }, data: { formation: '4-4-2' } })
  console.log('errors:', JSON.stringify(errs))
  assert(errs.length === 0, 'no console errors')
  await b.close()
})().catch(e => { console.error('E2E FAIL', e.message); process.exit(1) })

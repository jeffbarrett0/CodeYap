// Frame tools: arrow, circle, line, link, run arrow, area, number, player, spotlight; select + move by the middle,
// resize handles, delete, drawing duration, region zoom, seek bar, Screenshot.
const { chromium } = require('playwright')
const SP = process.argv[2] || './e2e-out'
require('fs').mkdirSync(SP, { recursive: true })
const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); console.log('  ok -', m) }
;(async () => {
  const b = await chromium.launch()
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()))
  p.on('dialog', d => d.accept('Marcus'))
  await p.goto('http://localhost:4000/match/m_demo', { waitUntil: 'networkidle' })
  await p.waitForFunction(() => document.querySelector('video')?.readyState >= 2)
  await p.evaluate(() => { document.querySelector('video').currentTime = 20 }); await p.waitForTimeout(400)
  const tb = p.getByRole('toolbar', { name: 'Frame tools' })
  for (const n of ['Seç', 'Ok', 'Daire', 'Çizgi', 'Bağlantı', 'Koşu oku', 'Alan', 'Numara', 'Oyuncu', 'Aydınlat', 'Kaydır']) assert(await tb.getByRole('button', { name: n, exact: true }).count() === 1, `tool "${n}" exists`)
  const svg = p.locator('svg[aria-label="Drawing overlay"]')
  const box = await svg.boundingBox()
  const X = (f) => box.x + f * box.width, Y = (f) => box.y + f * box.height
  const shapes = () => p.locator('svg[aria-label="Drawing overlay"] g[data-shape]')
  const types = () => shapes().evaluateAll(g => g.map(x => x.dataset.shape))
  const drag = async (x1, y1, x2, y2) => { await p.mouse.move(x1, y1); await p.mouse.down(); await p.mouse.move(x2, y2, { steps: 6 }); await p.mouse.up() }
  const tool = (n) => tb.getByRole('button', { name: n, exact: true }).click()
  const geom = async (t) => p.locator(`g[data-shape="${t}"] line`).first().evaluate(l => [+l.getAttribute('x1'), +l.getAttribute('y1'), +l.getAttribute('x2'), +l.getAttribute('y2')])

  console.log('Line: draw, move by its middle, resize by handle')
  await tool('Çizgi'); await drag(X(0.1), Y(0.2), X(0.3), Y(0.2))
  assert(await shapes().count() === 1, 'a line is drawn')
  const g0 = await geom('line')
  await drag(X(0.2), Y(0.2), X(0.2) + 60, Y(0.2) + 70)
  const g1 = await geom('line')
  assert(Math.abs(Math.hypot(g0[2] - g0[0], g0[3] - g0[1]) - Math.hypot(g1[2] - g1[0], g1[3] - g1[1])) < 1 && g1[0] > g0[0] + 30 && g1[1] > g0[1] + 30, 'dragging the middle moves the whole line')
  assert(await shapes().count() === 1, 'moving did not create a second shape')
  const hb = await p.locator('circle[data-handle="2"]').boundingBox()
  await drag(hb.x + hb.width / 2, hb.y + hb.height / 2, hb.x + 120, hb.y + 10)
  const g2 = await geom('line')
  assert(Math.hypot(g2[2] - g2[0], g2[3] - g2[1]) > Math.hypot(g1[2] - g1[0], g1[3] - g1[1]) + 20 && Math.abs(g2[0] - g1[0]) < 1, 'an end handle resizes; the other end stays')

  console.log('Arrow, circle, link, run arrow, spotlight')
  await tool('Ok'); await drag(X(0.4), Y(0.93), X(0.6), Y(0.93))
  await tool('Daire')
  const sx = X(0.12), sy = Y(0.5), ex = sx + 70, ey = sy + 70
  await drag(sx, sy, ex, ey)
  const el0 = await p.locator('g[data-shape="circle"] ellipse').first().evaluate(e => { const r = e.getBoundingClientRect(); return [r.left, r.top, r.right, r.bottom] })
  assert(Math.abs(el0[0] - sx) < 14 && Math.abs(el0[1] - sy) < 14 && Math.abs(el0[2] - ex) < 14 && Math.abs(el0[3] - ey) < 14, 'circle fills the dragged box (not reversed)')
  await tool('Bağlantı'); await drag(X(0.35), Y(0.6), X(0.55), Y(0.85))
  await tool('Koşu oku'); await drag(X(0.62), Y(0.62), X(0.85), Y(0.85))
  await tool('Aydınlat'); await drag(X(0.86), Y(0.08), X(0.97), Y(0.22))
  const t1 = await types()
  assert(['line', 'arrow', 'circle', 'link', 'run', 'spot'].every(t => t1.includes(t)), 'line, arrow, circle, link, run arrow and spotlight exist: ' + t1)
  assert(await p.locator('g[data-shape="link"] ellipse').count() === 2, 'a link has a ring on both players')
  assert(await p.locator('g[data-shape="run"] polygon').count() === 1, 'a run arrow has an arrow head')
  assert(await p.locator('svg[aria-label="Drawing overlay"] path[fill-rule="evenodd"]').count() === 1, 'spotlight dims the outside')
  // move circle by its middle while a draw tool is active
  const cen = () => p.locator('g[data-shape="circle"] ellipse').first().evaluate(c => [+c.getAttribute('cx'), +c.getAttribute('cy'), +c.getAttribute('rx')])
  const before = await cen()
  await drag((sx + ex) / 2, (sy + ey) / 2, (sx + ex) / 2 + 40, (sy + ey) / 2 - 20)
  const after = await cen()
  assert(after[0] > before[0] + 15 && Math.abs(after[2] - before[2]) < 0.5 && await shapes().count() === 6, 'grabbing the circle moves it (no new shape, same size)')
  await tool('Daire'); await p.keyboard.down('Shift'); await drag(X(0.7), Y(0.1), X(0.7) + 120, Y(0.1) + 30); await p.keyboard.up('Shift')
  const sq = await p.locator('g[data-shape="circle"] ellipse').last().evaluate(e => [+e.getAttribute('rx'), +e.getAttribute('ry')])
  assert(Math.abs(sq[0] - sq[1]) < 0.5, 'Shift gives a perfect circle')

  console.log('Number, player, area (on a clean frame)')
  await p.keyboard.press('ArrowRight'); await p.waitForTimeout(300)
  assert(await shapes().count() === 0, 'the next frame is clean')
  await tool('Numara'); await p.mouse.click(X(0.45), Y(0.2)); await p.mouse.click(X(0.55), Y(0.15))
  const nums = await p.locator('g[data-shape="number"] text').evaluateAll(t => t.map(x => x.textContent))
  assert(nums.join() === '1,2', 'numbers count 1, 2, …: ' + nums)
  await tool('Oyuncu'); await p.mouse.click(X(0.3), Y(0.32))
  assert((await p.locator('g[data-shape="player"] text').textContent()) === 'Oyuncu', 'player tag placed')
  await tool('Seç'); await p.locator('g[data-shape="player"] rect').dblclick(); await p.waitForTimeout(300)
  assert((await p.locator('g[data-shape="player"] text').textContent()) === 'Marcus', 'double-click renames the player tag')
  await tool('Alan')
  await p.mouse.click(X(0.62), Y(0.15)); await p.mouse.click(X(0.68), Y(0.4)); await p.mouse.click(X(0.8), Y(0.38)); await p.mouse.dblclick(X(0.82), Y(0.18))
  assert(await p.locator('g[data-shape="area"] polygon').count() === 2, 'area polygon (hatched) closed with a double-click')
  assert(await p.locator('g[data-shape="area"] circle[data-handle]').count() >= 3, 'area has a handle per corner')
  await p.screenshot({ path: `${SP}/frame-tools.png` })

  console.log('Select, delete, drawing duration')
  await tool('Seç')
  await p.mouse.click(X(0.72), Y(0.3)) // inside the area
  assert(await p.locator('g[data-selected]').count() === 1, 'click selects a drawing')
  const n0 = await shapes().count()
  await p.keyboard.press('Delete')
  assert(await shapes().count() === n0 - 1, 'Delete removes the selected drawing')
  await tb.getByRole('button', { name: 'Seçili çizimi sil' }).isDisabled().then(d => assert(d, 'trash is disabled when nothing is selected'))
  assert((await (await fetch('http://localhost:4000/api/clips?matchId=m_demo')).json()).length === 30, 'no clip was deleted')
  await p.selectOption('select[aria-label="Çizim süresi"]', '3')
  await tool('Çizgi'); await drag(X(0.1), Y(0.9), X(0.25), Y(0.9)); await tool('Seç')
  for (let i = 0; i < 20; i++) await p.keyboard.press('ArrowRight')
  await p.waitForTimeout(200)
  assert(await p.locator('g[data-shape="line"]').count() === 1, 'a drawing with a 3 s duration stays visible on later frames')
  await p.keyboard.press('Control+z'); await p.waitForTimeout(100)
  for (let i = 0; i < 20; i++) await p.keyboard.press('ArrowLeft')
  await p.waitForTimeout(200)

  console.log('Zoom to region + readout')
  assert((await tb.getByRole('button', { name: /Zoom'u sıfırla/ }).innerText()).trim() === '1.00×', 'zoom starts at 1.00×')
  await tb.getByRole('button', { name: 'Bölgeye yakınlaştır' }).click()
  await drag(X(0.45), Y(0.25), X(0.7), Y(0.6))
  const z = parseFloat(await tb.getByRole('button', { name: /Zoom'u sıfırla/ }).innerText())
  assert(z > 2.5, `dragging a region zooms into it (${z.toFixed(2)}×)`)
  await tb.getByRole('button', { name: 'Uzaklaş' }).click()
  assert(parseFloat(await tb.getByRole('button', { name: /Zoom'u sıfırla/ }).innerText()) < z, 'zoom out works')
  await tb.getByRole('button', { name: /Zoom'u sıfırla/ }).click()
  assert((await tb.getByRole('button', { name: /Zoom'u sıfırla/ }).innerText()).trim() === '1.00×', 'zoom resets')
  await p.getByLabel('Video boyutu').fill('60'); await p.waitForTimeout(200)
  const vw = (await p.locator('video').boundingBox()).width
  await p.getByLabel('Video boyutu').fill('100'); await p.waitForTimeout(200)
  assert((await p.locator('video').boundingBox()).width > vw * 1.4, 'Video boyutu slider resizes the video')

  console.log('Seek bar + screenshot button')
  const bb = await p.getByRole('slider', { name: 'Seek' }).boundingBox()
  await p.mouse.click(bb.x + bb.width * 0.5, bb.y + bb.height / 2); await p.waitForTimeout(400)
  const t90 = await p.evaluate(() => document.querySelector('video').currentTime)
  assert(Math.abs(t90 - 90) < 2.5, `seek bar middle jumps to ~1:30 (${t90.toFixed(1)}s)`)
  await p.getByLabel('Go to time (minutes or m:ss)').fill('2'); await p.keyboard.press('Enter'); await p.waitForTimeout(400)
  assert(Math.abs((await p.evaluate(() => document.querySelector('video').currentTime)) - 120) < 1, '"2" in Go-to jumps to minute 2')
  const dl = p.waitForEvent('download'); await p.getByRole('button', { name: 'Ekran görüntüsü al' }).click(); const d = await dl
  await d.saveAs(`${SP}/clean-shot.png`)
  assert(require('fs').statSync(`${SP}/clean-shot.png`).size > 20000 && /\.png$/.test(d.suggestedFilename()), 'Ekran görüntüsü al downloads a PNG')

  console.log('errors:', JSON.stringify(errs)); assert(errs.length === 0, 'no console errors')
  await b.close()
})().catch(e => { console.error('E2E FAIL', e.message); process.exit(1) })

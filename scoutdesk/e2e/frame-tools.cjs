// Frame tools: draw line/arrow/circle/box/spotlight, select + move by the middle, resize handles, delete, zoom to region.
const { chromium } = require('playwright')
const SP = process.argv[2] || './e2e-out'
require('fs').mkdirSync(SP, { recursive: true })
const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); console.log('  ok -', m) }
;(async () => {
  const b = await chromium.launch()
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()))
  await p.goto('http://localhost:4000/match/m_demo', { waitUntil: 'networkidle' })
  await p.waitForFunction(() => document.querySelector('video')?.readyState >= 2)
  await p.evaluate(() => { document.querySelector('video').currentTime = 20 }); await p.waitForTimeout(400)
  const tb = p.getByRole('toolbar', { name: 'Frame tools' })
  assert(await tb.getByRole('button').count() >= 10, 'FRAME TOOLS bar is always visible')
  const svg = p.locator('svg[aria-label="Drawing overlay"]')
  const box = await svg.boundingBox()
  const shapes = () => p.locator('svg[aria-label="Drawing overlay"] g[data-shape]')
  const geom = async (sel) => p.locator(`svg[aria-label="Drawing overlay"] g[data-shape="${sel}"] line`).first().evaluate(l => [+l.getAttribute('x1'), +l.getAttribute('y1'), +l.getAttribute('x2'), +l.getAttribute('y2')])

  console.log('Line: draw, then move by its middle')
  await tb.getByRole('button', { name: 'Line' }).click()
  await p.mouse.move(box.x + 100, box.y + 100); await p.mouse.down(); await p.mouse.move(box.x + 300, box.y + 100, { steps: 6 }); await p.mouse.up()
  assert(await shapes().count() === 1, 'a line is drawn')
  const g0 = await geom('line')
  // grab the middle (200,100) and drag down-right by (60, 80) screen px
  await p.mouse.move(box.x + 200, box.y + 100); await p.mouse.down(); await p.mouse.move(box.x + 260, box.y + 180, { steps: 8 }); await p.mouse.up()
  const g1 = await geom('line')
  const len0 = Math.hypot(g0[2] - g0[0], g0[3] - g0[1]), len1 = Math.hypot(g1[2] - g1[0], g1[3] - g1[1])
  assert(Math.abs(len0 - len1) < 1 && g1[0] > g0[0] + 30 && g1[1] > g0[1] + 30, `dragging the middle moves the whole line (x ${g0[0].toFixed(0)}→${g1[0].toFixed(0)}, y ${g0[1].toFixed(0)}→${g1[1].toFixed(0)}, length unchanged)`)
  assert(await shapes().count() === 1, 'moving did not create a second shape')

  console.log('Handles resize')
  const h2 = p.locator('circle[data-handle="2"]')
  const hb = await h2.boundingBox()
  await p.mouse.move(hb.x + hb.width / 2, hb.y + hb.height / 2); await p.mouse.down(); await p.mouse.move(hb.x + 120, hb.y + 40, { steps: 6 }); await p.mouse.up()
  const g2 = await geom('line')
  assert(Math.hypot(g2[2] - g2[0], g2[3] - g2[1]) > len1 + 40 && Math.abs(g2[0] - g1[0]) < 1, 'dragging an end handle resizes; the other end stays put')

  console.log('Arrow, circle, box, spotlight')
  const X = (f) => box.x + f * box.width, Y = (f) => box.y + f * box.height
  const drag = async (x1, y1, x2, y2) => { await p.mouse.move(x1, y1); await p.mouse.down(); await p.mouse.move(x2, y2, { steps: 6 }); await p.mouse.up() }
  await tb.getByRole('button', { name: 'Arrow' }).click(); await drag(X(0.55), Y(0.45), X(0.8), Y(0.3))
  await tb.getByRole('button', { name: 'Circle' }).click()
  // Draw corner-to-corner toward the lower right: the circle must sit INSIDE that box (not centred on the start point, not mirrored).
  const sx = X(0.12), sy = Y(0.22), ex = X(0.12) + 70, ey = Y(0.22) + 70
  await drag(sx, sy, ex, ey)
  const el0 = await p.locator('g[data-shape="circle"] ellipse').first().evaluate(e => { const r = e.getBoundingClientRect(); return [r.left, r.top, r.right, r.bottom] })
  assert(Math.abs(el0[0] - sx) < 14 && Math.abs(el0[1] - sy) < 14 && Math.abs(el0[2] - ex) < 14 && Math.abs(el0[3] - ey) < 14, `circle fills the dragged box (${el0.map(Math.round)} vs ${[sx, sy, ex, ey].map(Math.round)})`)
  await tb.getByRole('button', { name: 'Box' }).click(); await drag(X(0.08), Y(0.7), X(0.3), Y(0.92))
  await tb.getByRole('button', { name: 'Spotlight' }).click(); await drag(X(0.86), Y(0.08), X(0.97), Y(0.22))
  console.log('  shapes:', await shapes().evaluateAll(g => g.map(x => x.dataset.shape)))
  assert(await shapes().count() === 5, 'line, arrow, circle, box and spotlight all exist')
  assert(await p.locator('svg[aria-label="Drawing overlay"] path[fill-rule="evenodd"]').count() === 1, 'spotlight dims the area outside it')
  // move the circle by its centre while a draw tool is still active (no need to switch tools)
  const cen = async () => p.locator('g[data-shape="circle"] ellipse').first().evaluate(c => [+c.getAttribute('cx'), +c.getAttribute('cy'), +c.getAttribute('rx')])
  const before = await cen()
  await drag((sx + ex) / 2, (sy + ey) / 2, (sx + ex) / 2 + 80, (sy + ey) / 2 + 20) // grab the middle of the circle
  const after = await cen()
  assert(Math.abs(after[2] - before[2]) < 0.5, 'moving keeps the circle size')
  assert(after[0] > before[0] + 30 && await shapes().count() === 5, 'grabbing the circle moves it instead of drawing a new one')
  // resize with a corner handle, and Shift makes a perfect circle
  const hh = await p.locator('g[data-shape="circle"] circle[data-handle="2"]').boundingBox().catch(() => null)
  if (hh) { const r0 = (await cen())[2]; console.log('   top element at handle:', await p.evaluate(([x, y]) => { const e = document.elementFromPoint(x, y); return e ? e.tagName + ' ' + e.className.toString().slice(0, 90) + ' ' + (e.getAttribute('data-handle') || e.getAttribute('aria-label') || e.parentElement?.getAttribute('data-shape') || '') : 'none' }, [hh.x + hh.width / 2, hh.y + hh.height / 2])); console.log('   handle at', Math.round(hh.x), Math.round(hh.y), 'rx before', r0.toFixed(1), 'tool-selected', await p.locator('g[data-selected]').count()); await drag(hh.x + hh.width / 2, hh.y + hh.height / 2, hh.x + hh.width / 2 + 40, hh.y + hh.height / 2 + 10); console.log('   rx after', (await cen())[2].toFixed(1)); assert((await cen())[2] > before[2] + 10, 'dragging a corner handle resizes the circle') }
  await tb.getByRole('button', { name: 'Circle' }).click()
  await p.keyboard.down('Shift'); await drag(X(0.7), Y(0.12), X(0.7) + 120, Y(0.12) + 30); await p.keyboard.up('Shift')
  const sq = await p.locator('g[data-shape="circle"] ellipse').last().evaluate(e => [+e.getAttribute('rx'), +e.getAttribute('ry')])
  assert(Math.abs(sq[0] - sq[1]) < 0.5, 'Shift while drawing gives a perfect circle')
  await p.locator('g[data-shape="circle"]').last().evaluate(() => {})
  await tb.getByRole('button', { name: 'Select & move' }).click()
  await p.mouse.move(X(0.7) + 60, Y(0.12) + 60); await p.mouse.down(); await p.mouse.up()
  await tb.getByRole('button', { name: 'Delete selected drawing' }).click()
  await p.screenshot({ path: `${SP}/frame-tools.png` })

  console.log('Select tool, delete')
  await tb.getByRole('button', { name: 'Select & move' }).click()
  await p.mouse.move((sx + ex) / 2 + 80, (sy + ey) / 2 + 20) // circle centre now
  await p.mouse.down(); await p.mouse.up()
  assert(await p.locator('g[data-selected]').count() === 1, 'click selects a shape')
  await tb.getByRole('button', { name: 'Delete selected drawing' }).click()
  assert(await shapes().count() === 4, 'trash button deletes the selected shape')
  await p.mouse.move(X(0.19), Y(0.81)) // inside the box
  await p.mouse.down(); await p.mouse.up()
  await p.keyboard.press('Delete')
  assert(await shapes().count() === 3, 'Delete key removes the selected shape (not clips)')
  assert((await (await fetch('http://localhost:4000/api/clips?matchId=m_demo')).json()).length === 30, 'no clip was deleted')

  console.log('Snapshot with drawings + spotlight')
  const dl = p.waitForEvent('download')
  await p.getByRole('button', { name: 'Snapshot' }).click(); await p.getByRole('menuitem', { name: 'Download PNG' }).click()
  const d = await dl; await d.saveAs(`${SP}/frame-snapshot.png`)
  assert(require('fs').statSync(`${SP}/frame-snapshot.png`).size > 30000, 'snapshot exports with the shapes')

  console.log('Zoom to region + readout')
  assert((await tb.getByRole('button', { name: /Reset zoom/ }).innerText()).trim() === '1.00×', 'zoom readout starts at 1.00×')
  await p.keyboard.press('Escape')
  await tb.getByRole('button', { name: 'Zoom to region' }).click()
  await drag(X(0.45), Y(0.25), X(0.7), Y(0.6))
  const z = parseFloat(await tb.getByRole('button', { name: /Reset zoom/ }).innerText())
  assert(z > 2.5, `dragging a region zooms into it (${z.toFixed(2)}×)`)
  assert(await tb.getByRole('button', { name: 'Zoom to region' }).getAttribute('aria-pressed') === 'false', 'tool returns to Select afterwards')
  await p.screenshot({ path: `${SP}/frame-zoom.png` })
  await tb.getByRole('button', { name: 'Zoom out' }).click()
  assert(parseFloat(await tb.getByRole('button', { name: /Reset zoom/ }).innerText()) < z, 'zoom out works')
  await tb.getByRole('button', { name: /Reset zoom/ }).click()
  assert((await tb.getByRole('button', { name: /Reset zoom/ }).innerText()).trim() === '1.00×', 'readout resets to 1.00×')

  console.log('Seek bar + clean screenshot')
  const bar = p.getByRole('slider', { name: 'Seek' })
  const bb = await bar.boundingBox()
  await p.mouse.click(bb.x + bb.width * 0.5, bb.y + bb.height / 2); await p.waitForTimeout(400)
  const t90 = await p.evaluate(() => document.querySelector('video').currentTime)
  assert(Math.abs(t90 - 90) < 2.5, `clicking the middle of the seek bar jumps to ~1:30 (got ${t90.toFixed(1)}s)`)
  await p.getByLabel('Go to time (minutes or m:ss)').fill('2'); await p.keyboard.press('Enter'); await p.waitForTimeout(400)
  assert(Math.abs((await p.evaluate(() => document.querySelector('video').currentTime)) - 120) < 1, '"2" in Go-to jumps to minute 2 (2:00)')
  await p.getByLabel('Go to time (minutes or m:ss)').fill('0:45'); await p.keyboard.press('Enter'); await p.waitForTimeout(400)
  assert(Math.abs((await p.evaluate(() => document.querySelector('video').currentTime)) - 45) < 1, '"0:45" jumps to 45 s')
  assert(await p.locator('[aria-label="Seek"] span:has-text("1:00")').count() >= 1, 'minute ticks are labelled')
  await p.evaluate(() => { document.querySelector('video').currentTime = 20 }); await p.waitForTimeout(400)
  const dl2 = p.waitForEvent('download'); await tb.getByRole('button', { name: 'Screenshot' }).click(); const d2 = await dl2
  await d2.saveAs(`${SP}/clean-shot.png`)
  assert(require('fs').statSync(`${SP}/clean-shot.png`).size > 20000 && /\.png$/.test(d2.suggestedFilename()), 'Screenshot button downloads a PNG')
  await p.screenshot({ path: `${SP}/seekbar.png` })
  await p.evaluate(() => { document.querySelector('video').currentTime = 20 }); await p.waitForTimeout(400)

  console.log('Shapes follow their frame; undo')
  await p.keyboard.press('ArrowRight'); await p.waitForTimeout(200)
  assert(await shapes().count() === 0, 'shapes hide on another frame')
  await p.keyboard.press('ArrowLeft'); await p.waitForTimeout(200)
  assert(await shapes().count() === 3, 'and return on their frame')
  await p.keyboard.press('Control+z')
  assert(await shapes().count() === 2, 'Ctrl+Z removes the last drawing first')
  console.log('errors:', JSON.stringify(errs)); assert(errs.length === 0, 'no console errors')
  await b.close()
})().catch(e => { console.error('E2E FAIL', e.message); process.exit(1) })
